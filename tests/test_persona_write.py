"""Contracts for ``persona-extract --write``: safe filenames, ignored output, labelled files."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

from conversation_corpus_engine.paths import REPO_ROOT
from conversation_corpus_engine.persona_extract import (
    extract_persona_lexicon,
    write_persona_extract_artifacts,
)


def _payload(tmp_path: Path, persona: str = "rob", **extra: object) -> dict:
    payload = extract_persona_lexicon(tmp_path, "rob")
    return {**payload, "persona_id": persona, **extra}


def _files(root: Path) -> set[Path]:
    return {path for path in root.rglob("*") if path.is_file()}


@pytest.mark.parametrize(
    "persona",
    ["../escape", "a/b", "a\\b", "/abs", ".", "..", "...", "", "   ", "nul\x00byte"],
)
def test_unsafe_persona_ids_are_rejected_without_writing(tmp_path, persona):
    project = tmp_path / "project"
    project.mkdir()
    with pytest.raises(ValueError, match="persona"):
        write_persona_extract_artifacts(project, _payload(tmp_path, persona))
    assert _files(tmp_path) == set()


def test_unsafe_timestamp_is_rejected_without_writing(tmp_path):
    project = tmp_path / "project"
    project.mkdir()
    with pytest.raises(ValueError, match="timestamp"):
        write_persona_extract_artifacts(project, _payload(tmp_path, timestamp="../../x"))
    assert _files(tmp_path) == set()


def test_unusual_persona_ids_become_safe_collision_resistant_filename_tokens(tmp_path):
    output = tmp_path / "docs" / "storefront" / "_generated"
    names = set()
    for persona in ("rob smith", "rob?smith", "rob*smith"):
        json_path, markdown_path = write_persona_extract_artifacts(
            tmp_path, _payload(tmp_path, persona)
        )
        assert json_path.parent == output and markdown_path.parent == output
        assert json_path.name.startswith("persona-extract-rob-smith-")
        names.add(json_path.name)
        assert json.loads(json_path.read_text())["persona_id"] == persona
    assert len(names) == 3


def test_plain_persona_id_filename_is_unchanged(tmp_path):
    json_path, _ = write_persona_extract_artifacts(tmp_path, _payload(tmp_path, "rob"))
    assert json_path.name == "persona-extract-rob-latest.json"


def test_written_files_name_the_attribution_mode_in_a_leading_marker(tmp_path):
    payload = extract_persona_lexicon(tmp_path, "claude", allow_curated=True)
    json_path, markdown_path = write_persona_extract_artifacts(tmp_path, payload)
    marker = json.loads(json_path.read_text())["generated_marker"]
    assert marker["attribution_mode"] == "strict"
    assert marker["curated_fallback"] is True
    assert marker["overwrites_existing"] is True
    first_line = markdown_path.read_text().splitlines()[0]
    assert first_line.startswith("<!-- generated by cce persona-extract")
    assert "attribution_mode=strict" in first_line
    assert "curated_fallback=true" in first_line
    assert "overwritten" in first_line
    assert list(json.loads(json_path.read_text()))[0] == "generated_marker"


def test_dated_files_are_not_marked_as_overwriting(tmp_path):
    payload = _payload(tmp_path, timestamp="20260619")
    json_path, markdown_path = write_persona_extract_artifacts(tmp_path, payload)
    assert json.loads(json_path.read_text())["generated_marker"]["overwrites_existing"] is False
    assert "overwritten" not in markdown_path.read_text().splitlines()[0]


def test_latest_files_are_replaced_by_the_next_write(tmp_path):
    first, _ = write_persona_extract_artifacts(tmp_path, _payload(tmp_path, status="FIRST"))
    second, _ = write_persona_extract_artifacts(tmp_path, _payload(tmp_path, status="SECOND"))
    assert first == second
    assert json.loads(second.read_text())["status"] == "SECOND"


def test_generated_storefront_directory_is_git_ignored():
    if not (REPO_ROOT / ".git").exists():
        pytest.skip("not running from a git checkout")
    probe = "docs/storefront/_generated/persona-extract-rob-latest.json"
    result = subprocess.run(
        ["git", "check-ignore", "-q", probe],
        cwd=REPO_ROOT,
        env={"PATH": "/usr/bin:/bin:/usr/local/bin:/opt/homebrew/bin"},
        check=False,
    )
    assert result.returncode == 0
