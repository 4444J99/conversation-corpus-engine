"""Provenance of the user-role turns in a coding CLI's transcript.

A coding CLI writes everything the model is shown as a `user` turn. Most of those turns are not
the person's words:

* every prompt in a subagent's transcript was written by the parent agent;
* harness text is injected into user turns: system reminders, hook feedback, skill bodies,
  compaction summaries, command output, messages from other sessions;
* only what is left was typed (or pasted, or entered as a slash or shell command) by the person.

`classify_user_turn` decides which, from the session kind and the turn's leading text, and names
the basis so the decision stays auditable. The rule is deliberately precision-first: a tag-wrapped
turn it does not recognise is machine (`unclassified-tag:<name>`), never silently human, and the
basis counts travel in the provider manifest. Plain text that reads like a prompt is human; a
plain-text template the harness writes is listed in `HARNESS_PREFIXES`, and a template this list
misses stays human, so the human count of a CLI family is an upper bound that the manifest's
basis counts let a reader audit.
"""

from __future__ import annotations

import re
from collections import Counter

from .archive_model import Conversation

BASIS_KEY = "author_basis"
SUBAGENT = "subagent"
SYSTEM_CHANNEL = "system"

BASIS_TYPED = "typed"
BASIS_SUBAGENT = "subagent-prompt"
BASIS_HARNESS = "harness-text"

_LEADING_TAG = re.compile(r"^\s*<([A-Za-z_][\w:.-]{0,40})[\s>/]")

# A tag-wrapped turn that records something the person did: a slash command, a shell command they
# ran, text they pasted, an answer they gave to a question the agent asked.
TYPED_TAGS: frozenset[str] = frozenset(
    {
        "command-name",
        "command-message",
        "command-args",
        "bash-input",
        "user_shell_command",
        "pasted_content",
        "send_user_message_question_reply",
    }
)

# A tag-wrapped turn the harness or another agent wrote.
INJECTED_TAGS: frozenset[str] = frozenset(
    {
        "system-reminder",
        "system_reminder",
        "session_context",
        "agent_merge_state",
        "local-command-caveat",
        "local-command-stdout",
        "local-command-stderr",
        "bash-stdout",
        "bash-stderr",
        "task-notification",
        "agent-message",
        "teammate-message",
        "cross-session-message",
        "side-sessions-event",
        "ci-monitor-event",
        "user-prompt-submit-hook",
        "codex_internal_context",
        "codex_delegation",
        "realtime_delegation",
        "environment_context",
        "external_codex_apps_open_page",
        "external_codex_apps_writing_block_edits",
        "in-app-browser-context",
        "recommended_plugins",
        "skill",
        "heartbeat",
        "turn_aborted",
        "user_instructions",
        "subagent_notification",
        "collaboration_mode",
        "permissions",
        "context",
        "image",
        "INSTRUCTIONS",
    }
)

# Plain-text templates the harness writes into a user turn (compared after left-stripping).
HARNESS_PREFIXES: tuple[str, ...] = (
    "This session is being continued from a previous conversation",
    "Another Claude session sent a message:",
    "Base directory for this skill:",
    "Tool loaded.",
    "The user sent a new message while",
    "Stop hook feedback:",
    "[Request interrupted by user",
    "Caveat: The messages below were generated by the user while running local commands",
    "# AGENTS.md instructions",
    "A previous agent produced the plan below",
    "</image>",
    "# /loop",
    "# Workflow authoring reference",
    "# Claude Code Doctor",
)
_LOOP_WAKEUP = re.compile(r"^\[\d+ prior /loop wakeups?")


def classify_user_turn(text: str, session_kind: str) -> tuple[bool, str]:
    """(typed by the person, basis) for one user-role turn of a coding CLI transcript."""
    if session_kind == SUBAGENT:
        return False, BASIS_SUBAGENT
    stripped = text.lstrip()
    if stripped.startswith(HARNESS_PREFIXES) or _LOOP_WAKEUP.match(stripped):
        return False, BASIS_HARNESS
    found = _LEADING_TAG.match(stripped)
    if found:
        tag = found.group(1)
        if tag in TYPED_TAGS:
            return True, f"{BASIS_TYPED}:{tag}"
        if tag in INJECTED_TAGS or tag.startswith("ide_"):
            return False, f"injected:{tag}"
        return False, f"unclassified-tag:{tag}"
    return True, BASIS_TYPED


def reclassify_typed_turns(conversation: Conversation) -> Counter[str]:
    """Move every user turn the person did not type off the `typed` channel; count the bases.

    A turn that stays human keeps channel `typed`; one that does not goes to channel `system`
    with `typed_chars` 0 (the person typed none of it). Every user turn that was on the `typed`
    channel gets `meta.author_basis`. The counter is keyed `human:<basis>` or `machine:<basis>`.
    """
    session_kind = str(conversation.extra.get("session_kind") or "")
    counts: Counter[str] = Counter()
    for message in conversation.messages:
        if message.role != "user" or message.channel != "typed":
            continue
        human, basis = classify_user_turn(message.text, session_kind)
        message.meta[BASIS_KEY] = basis
        if not human:
            message.channel = SYSTEM_CHANNEL
            message.typed_chars = 0
        counts[f"{'human' if human else 'machine'}:{basis}"] += 1
    return counts
