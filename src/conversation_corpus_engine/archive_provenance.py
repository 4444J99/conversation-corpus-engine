"""Provenance of the user-role turns in a coding CLI's transcript.

A coding CLI writes everything the model is shown as a `user` turn. Most of those turns are not
the person's words:

* every prompt in a subagent's transcript was written by the parent agent;
* harness text is injected into user turns: system reminders, hook feedback, skill bodies,
  compaction summaries, command output, messages from other sessions;
* only what is left was typed (or pasted, or entered as a slash or shell command) by the person.

`classify_user_turn` decides which, from the session kind and the turn's leading text, and names
the basis so the decision stays auditable. The rule is deliberately precision-first: a tag-wrapped
turn it does not recognise is machine (`unclassified-tag:<name>`), never silently human, and the
basis counts travel in the provider manifest. Plain text that reads like a prompt is human; a
plain-text template the harness writes is listed in `HARNESS_PREFIXES`, and a template this list
misses stays human, so the human count of a CLI family is an upper bound that the manifest's
basis counts let a reader audit.
"""

from __future__ import annotations

import re
from collections import Counter

from .archive_model import Conversation

BASIS_KEY = "author_basis"
SUBAGENT = "subagent"
SYSTEM_CHANNEL = "system"

BASIS_TYPED = "typed"
BASIS_SUBAGENT = "subagent-prompt"
BASIS_HARNESS = "harness-text"

_LEADING_TAG = re.compile(r"^\s*<([A-Za-z_][\w:.-]{0,40})[\s>/]")

# A tag-wrapped turn that records something the person did: a slash command, a shell command they
# ran, text they pasted, an answer they gave to a question the agent asked.
TYPED_TAGS: frozenset[str] = frozenset(
    {
        "command-name",
        "command-message",
        "command-args",
        "bash-input",
        "user_shell_command",
        "pasted_content",
        "send_user_message_question_reply",
    }
)

# A tag-wrapped turn the harness or another agent wrote.
INJECTED_TAGS: frozenset[str] = frozenset(
    {
        "system-reminder",
        "system_reminder",
        "session_context",
        "agent_merge_state",
        "local-command-caveat",
        "local-command-stdout",
        "local-command-stderr",
        "bash-stdout",
        "bash-stderr",
        "task-notification",
        "agent-message",
        "teammate-message",
        "cross-session-message",
        "side-sessions-event",
        "ci-monitor-event",
        "user-prompt-submit-hook",
        "codex_internal_context",
        "codex_delegation",
        "realtime_delegation",
        "environment_context",
        "external_codex_apps_open_page",
        "external_codex_apps_writing_block_edits",
        "in-app-browser-context",
        "recommended_plugins",
        "skill",
        "heartbeat",
        "turn_aborted",
        "user_instructions",
        "subagent_notification",
        "collaboration_mode",
        "permissions",
        "context",
        "image",
        "INSTRUCTIONS",
    }
)

# Plain-text templates the harness (or a dispatcher) writes into a user turn (compared after
# left-stripping). All were found verbatim in local CLI transcripts (claude/projects, codex
# sessions, opencode.db, copilot events, gemini tmp chats) prefixed exactly as listed; the
# opencode/gemini/copilot entries are automation-dispatch preambles, not person-typed turns.
HARNESS_PREFIXES: tuple[str, ...] = (
    "This session is being continued from a previous conversation",
    "Another Claude session sent a message",
    "The coordinator sent a message while you were working:",
    "Background (from the session that started this one):",
    "Base directory for this skill:",
    "Tool loaded.",
    "The user sent a new message while",
    "Stop hook feedback:",
    "[Request interrupted by user",
    "[Workflow harness",
    "[SYSTEM NOTIFICATION - NOT USER INPUT]",
    "A session-scoped Stop hook is now active with condition:",
    "Goal check-in: «",
    "Your response above was cut off mid-stream.",
    "Your response above was stopped by a safety classifier",
    "Skill /workflow-authoring is already loaded above; instructions unchanged.",
    "The following is a <SYSTEM_MESSAGE> not actually sent by the user.",
    "Caveat: The messages below were generated by the user while running local commands",
    "# AGENTS.md instructions",
    "A previous agent produced the plan below",
    "</image>",
    "# /loop",
    "# Workflow authoring reference",
    "# Claude Code Doctor",
    "# FLAME — the Continuity Kernel",
    "You are a subagent spawned by another session.",
    "You are a worker in the autonomous development team.",
    "[Scheduled prompt #",
    "[PR COMMENT FIX REQUEST",
    "[PR CHECK FIX REQUEST",
    "[structured-output-enforce]",
    "[handback-send-enforce]",
    "[Cross-session idle notice]",
    "You are an independent code reviewer.",
    "You are a subagent handling",
    "You are working in a local workspace for a pull request this project opened.",
    "You are working in a git worktree at:",
    "You are working in PR ",
    "Read-only web verification.",
    "Independently review a docs-only change in the git worktree",
    "Evaluate only these comments on merged PR",
    "Name this chat from the user's first request.",
    "The user explicitly invoked the \"/closeout\" skill. Follow its instructions now.",
    "# Autonomous loop tick (dynamic pacing)",
    "# Autonomous loop check",
    "## Context Usage",
    "# Pull Request Creation",
)
_LOOP_WAKEUP = re.compile(r"^\[\d+ prior /loop wakeups?")


def classify_user_turn(
    text: str, session_kind: str, parent_session_id: str = ""
) -> tuple[bool, str]:
    """(typed by the person, basis) for one user-role turn of a coding CLI transcript.

    A session that names a parent is a child the parent agent spawned, even when its
    ``session_kind`` reads ``root``: the parent wrote every prompt of that transcript.
    """
    if session_kind == SUBAGENT or parent_session_id:
        return False, BASIS_SUBAGENT
    stripped = text.lstrip()
    if stripped.startswith(HARNESS_PREFIXES) or _LOOP_WAKEUP.match(stripped):
        return False, BASIS_HARNESS
    found = _LEADING_TAG.match(stripped)
    if found:
        tag = found.group(1)
        if tag in TYPED_TAGS:
            return True, f"{BASIS_TYPED}:{tag}"
        if tag in INJECTED_TAGS or tag.startswith("ide_"):
            return False, f"injected:{tag}"
        return False, f"unclassified-tag:{tag}"
    return True, BASIS_TYPED


def reclassify_typed_turns(conversation: Conversation) -> Counter[str]:
    """Move every user turn the person did not type off the `typed` channel; count the bases.

    A turn that stays human keeps channel `typed`; one that does not goes to channel `system`
    with `typed_chars` 0 (the person typed none of it). Every user turn that was on the `typed`
    channel gets `meta.author_basis`. The counter is keyed `human:<basis>` or `machine:<basis>`.
    """
    session_kind = str(conversation.extra.get("session_kind") or "")
    parent = str(conversation.extra.get("parent_session_id") or "")
    counts: Counter[str] = Counter()
    # The two spawn signals disagree when exactly one of them fires: a `subagent` with no
    # parent recorded, or a `root`/`unknown` with one. Count the disagreements per family
    # (`diagnostic:kind-parent-disagreement`) so a future audit can see the fields are
    # unreliable for that family; the parent signal wins either way.
    if (session_kind == SUBAGENT) != bool(parent):
        counts["diagnostic:kind-parent-disagreement"] += 1
    for message in conversation.messages:
        if message.role != "user" or message.channel != "typed":
            continue
        human, basis = classify_user_turn(message.text, session_kind, parent)
        message.meta[BASIS_KEY] = basis
        if not human:
            message.channel = SYSTEM_CHANNEL
            message.typed_chars = 0
        counts[f"{'human' if human else 'machine'}:{basis}"] += 1
    return counts
